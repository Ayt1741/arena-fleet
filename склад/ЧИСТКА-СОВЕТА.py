# -*- coding: utf-8 -*-
"""ЧИСТКА СОВЕТА — убирает английские рассуждения модели и ставит оценку качеству.

Модель иногда печатает «рассуждения» по-английски вместо ответа. Скрипт оставляет
только русские строки ответа и список источников, а каждому файлу ставит оценку:
  ГОДЕН     — русский ответ есть, ссылок ≥ 3, среди доменов нет только мусорных;
  ЧАСТИЧНО  — русский ответ есть, но источники слабые;
  БРАК      — английские рассуждения вместо ответа.

Запуск:  python ЧИСТКА-СОВЕТА.py <папка с L*.md>
"""
import glob
import os
import re
import sys

ПАПКА = sys.argv[1] if len(sys.argv) > 1 else 'state/leaders-capacity'
МУСОР = {'github.com', 'en.wikipedia.org', 'youtube.com', 'medium.com'}


def русская(строка):
    return len(re.findall(r'[а-яА-Я]', строка)) >= 3


def чистить(текст):
    строки = текст.split('\n')
    шапка, источники, тело = [], [], []
    режим = 'шапка'
    for s in строки:
        if s.startswith('## Источники'):
            режим = 'источники'
        if режим == 'шапка':
            шапка.append(s)
        elif режим == 'источники':
            источники.append(s)
        else:
            тело.append(s)
    чистое = [s for s in тело if русская(s) or not s.strip() or re.match(r'^\s*[-*\d]', s)]
    # выбрасываем строки, где английских букв больше, чем русских
    итог = []
    for s in чистое:
        if len(re.findall(r'[a-zA-Z]', s)) > 2 * len(re.findall(r'[а-яА-Я]', s)) and not re.match(r'^\s*\[?\d', s):
            continue
        итог.append(s)
    return '\n'.join(шапка + итог + источники).strip() + '\n'


def оценка(текст):
    ru = len(re.findall(r'[а-яА-Я]', текст))
    en = len(re.findall(r'[a-zA-Z]', текст))
    домены = {re.sub(r'https?://', '', u).split('/')[0] for u in re.findall(r'https?://[^\s\)\]|]+', текст)}
    ссылок = len(re.findall(r'https?://', текст))
    полезных = домены - МУСОР
    if ru < 200 or ru * 2 < en:
        return 'БРАК', ru, en, ссылок, домены
    if ссылок < 3 or not полезных:
        return 'ЧАСТИЧНО', ru, en, ссылок, домены
    return 'ГОДЕН', ru, en, ссылок, домены


def main():
    файлы = sorted(glob.glob(os.path.join(ПАПКА, 'L*.md')))
    строки = []
    итог = {'ГОДЕН': 0, 'ЧАСТИЧНО': 0, 'БРАК': 0}
    for f in файлы:
        было = open(f, encoding='utf-8').read()
        стало = чистить(было)
        open(f, 'w', encoding='utf-8').write(стало)
        в, ru, en, ссылок, домены = оценка(стало)
        итог[в] += 1
        строки.append('| %s | %s | %d | %d | %d | %s |' % (os.path.basename(f), в, ru, en, ссылок,
                                                          ', '.join(sorted(домены)[:4])))
    таблица = ('# КАЧЕСТВО МАТЕРИАЛОВ СОВЕТА\n\n'
               '| файл | оценка | русских букв | английских | ссылок | домены |\n|---|---|---|---|---|---|\n'
               + '\n'.join(строки) +
               '\n\nИтог: годен %(ГОДЕН)d, частично %(ЧАСТИЧНО)d, брак %(БРАК)d.\n' % итог)
    open(os.path.join(ПАПКА, 'КАЧЕСТВО.md'), 'w', encoding='utf-8').write(таблица)
    print(таблица)


if __name__ == '__main__':
    main()
